class MsgHeaderTest(unittest.TestCase):
    GMM = """\
<?xml version="1.0"?>
<body language="English">
\t<row id="m_00000" index="0">
\t\t<attribute name="window_context_name">used</attribute>
\t\t<language name="English">EXIT</language>
\t</row>
\t<row id="m_00001" index="1">
\t\t<attribute name="window_context_name">garbage</attribute>
\t\t<language name="English">ABC</language>
\t\t<language name="日本語">日本語</language>
\t</row>
\t<row index="2">
\t\t<attribute name="window_context_name">used</attribute>
\t\t<language name="English">NOID</language>
\t</row>
</body>
"""

    def test_parse_and_render(self):
        rows = ph.parse_gmm_rows("files/msgdata/msg/m.gmm", self.GMM)
        # No real row lacks an id; the fallback keeps upstream's quirk
        # (length bound from the full path, applied to the basename, so the
        # extension survives): "m.gmm_00002".
        self.assertEqual([r[0] for r in rows],
                         ["m_00000", "m_00001", "m.gmm_00002"])
        # Garbage row: Japanese bytes blanked to spaces.
        self.assertEqual(rows[1][1], b" " * len("日本語".encode("utf-8")))
        text = ph.render_msg_header("files/msgdata/msg/m.h", rows)
        if isinstance(text, bytes):
            text = text.decode("utf-8")
        self.assertIn("#ifndef MSGENC_FILES_MSGDATA_MSG_M_H\n", text)
        self.assertIn("// EXIT\n#define m_00000 0\n", text)
        self.assertIn("#define m.gmm_00002 2\n", text)
        self.assertTrue(text.endswith("#endif //MSGENC_FILES_MSGDATA_MSG_M_H\n"))

    def test_split_300_bytes(self):
        # Byte-based chunks like C++ substr (limit 300), not characters.
        data = b"y" * 700
        self.assertEqual([len(c) for c in ph.split_message(data)],
                         [300, 300, 100])
        self.assertEqual(ph.split_message(b""), [])


class MkParseTest(unittest.TestCase):
    def test_parse_make_list(self):
        text = "FOO_FILES := \\\n\ta.b \\\n\tc.d\nOTHER := x\n"
        self.assertEqual(ph.parse_make_list(text, "FOO_FILES"), ["a.b", "c.d"])
        with self.assertRaises(ValueError):
            ph.parse_make_list(text, "MISSING")

    def test_strip_shortname_case(self):
        # The .mk sed is case-sensitive: lowercase entries strip, guards keep.
        self.assertEqual(ph.strip_shortname("NARC_zukan_enc_silver_x", "silver"),
                         "NARC_zukan_enc_x")
        self.assertEqual(ph.strip_shortname("NARC_ZUKAN_ENC_SILVER_NAIX_", "silver"),
                         "NARC_ZUKAN_ENC_SILVER_NAIX_")

    def test_zukan_data_names(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            data = {"sorting": [
                {"type": "t", "options": [{"id": "a"}, {"id": "b"}]},
            ]}
            target = root / "files/application/zukanlist/zkn_data"
            target.mkdir(parents=True)
            (target / "zukan_data.json").write_text(
                __import__("json").dumps(data), encoding="utf-8")
            names = ph.zukan_data_names(root)
            self.assertEqual(len(names), 13)
            self.assertEqual(names[0], "mon_stats_height")
            self.assertEqual(names[11:], ["sort_order_t_a", "sort_order_t_b"])

    def test_num_species(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            inc = root / "include/constants"
            inc.mkdir(parents=True)
            (inc / "species.h").write_text(
                "#define SPECIES_ROTOM_MOW       507\n", encoding="utf-8")
            self.assertEqual(ph.num_species(root), 507)
            with self.assertRaises(ValueError):
                ph.num_species(root / "include")


class OverlayIdsTest(unittest.TestCase):
    LSF = """\
Static main
{
\tAddress 0x02000000
\tObject src/main.o
}

Overlay first
{
\tAfter main
\tObject src/a.o
}

Overlay second
{
\tAfter first
\tObject src/b.o
}
"""

    def test_generate_overlay_ids(self):
        import game_overlays as go
        names = go.overlay_names(self.LSF)
        self.assertEqual(names, ["first", "second"])
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "main.lsf").write_text(self.LSF, encoding="utf-8")
            ld = Path(tmp) / "overlay_ids.ld"
            header = Path(tmp) / "overlay_ids.h"
            results = ph.generate_overlay_ids(root, ld, header)
            self.assertEqual(len(results), 2)
            self.assertIn("SDK_OVERLAY_first_ID = 0;",
                          ld.read_text(encoding="utf-8"))
            self.assertIn("SDK_PORT_OVERLAY_ID_second = 1,",
                          header.read_text(encoding="utf-8"))
            # Idempotent: second call rewrites nothing.
            results = ph.generate_overlay_ids(root, ld, header)
            self.assertEqual([changed for _, changed in results], [False, False])

    def test_no_outputs_no_work(self):
        with tempfile.TemporaryDirectory() as tmp:
            self.assertEqual(
                ph.generate_overlay_ids(Path(tmp), None, None), [])


