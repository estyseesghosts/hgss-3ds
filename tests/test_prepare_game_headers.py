class NitroarcRenderTest(unittest.TestCase):
    def test_exact(self):
        # Byte port of write_index(): header, dup suffixes, COUNT, footer.
        text = ph.render_nitroarc_naix(
            "files/data/namein.narc",
            ["namein_00000000.NCLR", "dup.bin", "dup.bin"])
        self.assertEqual(text, """\
/*
 * This file was generated by nitroarc for 'files/data/namein.narc'
 * DO NOT MODIFY IT; MANUAL EDITS WILL BE LOST
 */

#ifndef files_data_namein_naix
#define files_data_namein_naix

#define NARC_namein_namein_00000000_NCLR 0
#define NARC_namein_dup_bin 1
#define NARC_namein_dup_bin_1 2

#define files_data_namein_COUNT 3

#endif /* files_data_namein_naix */
""")

    def test_member_order(self):
        # Explicit .narcorder entries keep file order; the implicit tail is
        # sorted in byte order; excludes apply to the tail only.
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            for name in ("b.bin", "a.bin", ".narcignore", "x.png"):
                (root / name).write_text("x", encoding="utf-8")
            (root / "sub").mkdir()
            (root / "sub" / "c.bin").write_text("x", encoding="utf-8")
            (root / ".narcignore").write_text("*.png\n", encoding="utf-8")
            order = ["b.bin"]
            excludes = ph.default_excludes() + ph.read_dotfile(
                root / ".narcignore")
            got = ph.nitroarc_members(root, order, excludes)
            self.assertEqual(got, ["b.bin", "a.bin", "sub/c.bin"])
            # .narcignore/.narcorder-style dotfiles never leak through.
            self.assertNotIn(".narcignore", got)


